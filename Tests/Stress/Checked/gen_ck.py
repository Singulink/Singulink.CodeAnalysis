# Generates CK.cs: every narrow type, every compound operator and increment, in every form of checked context, each after a commit
# and between the read and the assignment of a [MovedFrom] parameter, with values that overflow. An accepted case that releases
# one acquisition twice is a miss. Usage: python gen_ck.py
TYPES = {
    # name: (initial value, operand for + - *, operand for | & ^)
    'byte': ('200', '(byte)100', '(byte)1'), 'sbyte': ('-100', '(sbyte)100', '(sbyte)1'), 'short': ('30000', '(short)10000', '(short)1'),
    'ushort': ('60000', '(ushort)10000', '(ushort)1'), 'char': ("'\\uFFF0'", "(char)100", "(char)1"),
    'int': ('int.MaxValue', '1', '1'), 'uint': ('uint.MaxValue', '1u', '1u'), 'long': ('long.MaxValue', '1L', '1L'), 'ulong': ('ulong.MaxValue', '1ul', '1ul'),
    'nint': ('nint.MaxValue', '(nint)1', '(nint)1'), 'nuint': ('nuint.MaxValue', '(nuint)1', '(nuint)1'),
    'EB': ('(EB)200', '(byte)100', 'EB.A'), 'ES': ('(ES)(-100)', '(sbyte)100', 'ES.A'), 'EI': ('(EI)int.MaxValue', '1', 'EI.A'),
}
NULLABLE = ['byte', 'sbyte', 'short', 'ushort', 'char', 'int', 'uint', 'EB']
OPS_NUM = ['+= {a}', '-= {neg}', '*= {m}', '<<= 1', '<<= 2', '>>= 1', '>>>= 1', '|= {b}', '&= {b}', '^= {b}', '/= {a}', '%= {a}', '++', '--', 'pre++', 'pre--']
OPS_ENUM = ['+= {a}', '-= {neg}', '|= {b}', '&= {b}', '^= {b}', '++', '--', 'pre++', 'pre--']


def stmt(target, op, t):
    init, a, b = TYPES[t]
    neg = a  # a subtraction from a small value overflows too: the initial values are near the top, so use the operand on the minimum below
    m = a if not t.startswith('E') else a
    if op == '++':
        return f'{target}++;'
    if op == '--':
        return f'{target}--;'
    if op == 'pre++':
        return f'++{target};'
    if op == 'pre--':
        return f'--{target};'
    return f'{target} {op.format(a=a, neg=neg, m=m, b=b)};'


def low(t):
    return {'byte': '0', 'sbyte': 'sbyte.MinValue', 'short': 'short.MinValue', 'ushort': '0', 'char': "'\\0'", 'int': 'int.MinValue', 'uint': '0',
            'long': 'long.MinValue', 'ulong': '0', 'nint': 'nint.MinValue', 'nuint': '0', 'EB': '(EB)0', 'ES': '(ES)sbyte.MinValue', 'EI': '(EI)int.MinValue'}[t]


CONTEXTS = {
    # name: (wrapper of a statement S, what the C# context is: 'checked' or 'unchecked' or 'project')
    'block': ('checked {{ {S} }}', 'checked'),
    'expr': ('_ = checked({E});', 'checked'),
    'none': ('{S}', 'project'),
    'unchecked': ('unchecked {{ {S} }}', 'unchecked'),
    'nested_cu': ('checked {{ unchecked {{ {S} }} }}', 'unchecked'),
    'nested_uc': ('unchecked {{ checked {{ {S} }} }}', 'checked'),
    'expr_in_unchecked': ('unchecked {{ _ = checked({E}); }}', 'checked'),
    'uexpr_in_checked': ('checked {{ _ = unchecked({E}); }}', 'unchecked'),
    'block_in_expr_lambda': ('{S}', 'project'),
}

out = ['// Generated by gen_ck.py.', 'using System;', 'using Singulink.CodeAnalysis;', '',
       'public enum EB : byte { A = 1 }', 'public enum ES : sbyte { A = 1 }', 'public enum EI { A = 1 }', '',
       'public sealed partial class Host', '{', '    public Guard F1;']
fields = []
cases = []
n = 0
for t in TYPES:
    for nullable in ([False, True] if t in NULLABLE else [False]):
        tt = t + ('?' if nullable else '')
        ops = OPS_ENUM if t.startswith('E') else OPS_NUM
        for op in ops:
            for start in ('high', 'low'):
                init = TYPES[t][0] if start == 'high' else low(t)
                for ctx, (wrap, kind) in CONTEXTS.items():
                    if ctx == 'block_in_expr_lambda':
                        continue
                    n += 1
                    f = f'V{n}'
                    fields.append(f'    public {tt} {f} = {init};')
                    s = stmt(f, op, t)
                    e = s.rstrip(';')
                    body = wrap.format(S=s, E=e)
                    cid = f'K{n:04d}'
                    cases.append((cid, f'{tt} {op} {start} {ctx}', body, f, tt, init, s, kind))

for cid, desc, body, f, tt, init, s, kind in cases:
    out += [f'    // CASE C{cid} {desc}', f'    public void C{cid}(Lock l)', '    {', '        Guard g = l.Enter();', '        try', '        {', '            F1 = g;',
            f'            {body}', '        }', '        catch { g.Dispose(); throw; }', '    }',
            f'    // CASE M{cid} {desc}', f'    public static void M{cid}([MovedFrom] ref Guard from, ref Guard to)', '    {', f'        {tt} v = {init};', '        to = from;',
            f'        {body.replace(f, "v")}', '        from = default;', '    }']

# Nested functions in a checked block, a lambda in a checked expression, a local function declared outside the block.
extra = [
    ('L01', 'checked { Action a = () => { Guard g = l.Enter(); try { F1 = g; NB <<= 1; } catch { g.Dispose(); throw; } }; a(); }'),
    ('L02', 'checked { void Local() { Guard g = l.Enter(); try { F1 = g; NB <<= 1; } catch { g.Dispose(); throw; } } Local(); }'),
    ('L03', 'Action a = checked((Action)(() => { Guard g = l.Enter(); try { F1 = g; NB <<= 1; } catch { g.Dispose(); throw; } })); a();'),
    ('L04', 'void Local() { Guard g = l.Enter(); try { F1 = g; NB <<= 1; } catch { g.Dispose(); throw; } } checked { Local(); }'),
    ('L05', 'checked { Action a = delegate { Guard g = l.Enter(); try { F1 = g; NB <<= 1; } catch { g.Dispose(); throw; } }; a(); }'),
    ('L06', 'checked { Action a = static () => { Guard g = St3.L.Enter(); try { St3.G = g; St3.NB <<= 1; } catch { g.Dispose(); throw; } }; a(); }'),
    ('L07', 'checked { Func<int> a = () => { Guard g = l.Enter(); try { F1 = g; NBN <<= 1; } catch { g.Dispose(); throw; } return 0; }; a(); }'),
    ('L08', 'checked { Action a = () => { unchecked { Guard g = l.Enter(); try { F1 = g; NB <<= 1; } catch { g.Dispose(); throw; } } }; a(); }'),
    ('L09', 'unchecked { Action a = () => { checked { Guard g = l.Enter(); try { F1 = g; NB <<= 1; } catch { g.Dispose(); throw; } } }; a(); }'),
    ('L10', 'checked { var q = System.Linq.Enumerable.Select(new[] { 1 }, x => { Guard g = l.Enter(); try { F1 = g; NB <<= 1; } catch { g.Dispose(); throw; } return x; }); foreach (var _ in q) { } }'),
]
for cid, body in extra:
    out += [f'    // CASE C{cid}', f'    public void C{cid}(Lock l)', '    {', f'        NB = 0x80; NBN = 0x80; {body}', '    }']
out += ['    public byte NB = 0x80; public byte? NBN = 0x80;']
# A field initializer and a static lambda field inside a checked expression.
out += ['    // CASE CI01', '    public Action<Lock> Init1 = checked((Action<Lock>)(l => { Guard g = l.Enter(); try { St3.G = g; St3.NB <<= 1; } catch { g.Dispose(); throw; } }));',
        '    // CASE CI02', '    public static Action<Lock> Init2 = l => { checked { Guard g = l.Enter(); try { St3.G = g; St3.NB <<= 1; } catch { g.Dispose(); throw; } } };',
        '    // CASE CI03', '    public Action<Lock> Init3 = l => { Guard g = l.Enter(); try { St3.G = g; St3.NB <<= 1; } catch { g.Dispose(); throw; } };', '    // END']
out += fields + ['}', '', 'public static class St3 { public static Lock L = new(); public static Guard G; public static byte NB = 0x80; }', '',
                 'public static partial class Program', '{',
                 '    static void Probe(string id, Action<Lock> body) { var l = new Lock(); string end = "returned"; try { body(l); } catch (Exception e) { end = e.GetType().Name; } Console.WriteLine($"{id}|{end}|{l.Report()}"); }',
                 '    public static void Main()', '    {']
for cid, *_ in cases:
    out.append(f'        Probe("C{cid}", l => {{ var h = new Host(); try {{ h.C{cid}(l); }} catch (OverflowException) {{ }} catch (DivideByZeroException) {{ }} h.F1.Dispose(); }});')
    out.append(f'        Probe("M{cid}", l => {{ Guard from = l.Enter(); Guard to = default; try {{ Host.M{cid}(ref from, ref to); }} catch (OverflowException) {{ }} from.Dispose(); to.Dispose(); }});')
for cid, _ in extra:
    out.append(f'        Probe("C{cid}", l => {{ var h = new Host(); St3.L = l; try {{ h.C{cid}(l); }} catch (OverflowException) {{ }} h.F1.Dispose(); St3.G.Dispose(); }});')
for i in (1, 2, 3):
    out.append(f'        Probe("CI0{i}", l => {{ var h = new Host(); St3.NB = 0x80; try {{ {"h.Init1" if i == 1 else "Host.Init2" if i == 2 else "h.Init3"}(l); }} catch (OverflowException) {{ }} St3.G.Dispose(); }});')
out += ['    }', '}']
open('CK.cs', 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
print(len(cases) * 2 + len(extra) + 3, 'cases')
